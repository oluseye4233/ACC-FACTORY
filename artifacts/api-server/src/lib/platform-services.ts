export function getPlatformServiceInventory(now = new Date()): InventoryWire {
  const services: PlatformService[] = DEFINITIONS.map((definition) => ({
    ...definition,
    scope: definition.stage === null ? "FUNCTION" : "STAGE",
    serviceReadiness: definition.implementation === "EXISTING" ? "EXISTING_UNVERIFIED" : definition.implementation,
    blockedReason: definition.implementation === "EXISTING" ? null : definition.limitations,
    sourceEligibility: "NOT_EVALUATED",
    entitlement: "NOT_EVALUATED",
    assessmentStatus: "NOT_EVALUATED",
    deliveryStatus: "NOT_EVALUATED",
    operationStatus: "NOT_EVALUATED",
    localAcceptance: "NOT_VERIFIED",
    productionAcceptance: "NOT_VERIFIED",
    evidenceCheckedAt: null,
    requiredEvidence: [
      "Service-specific acceptance against the current A contract, including safe failure and recovery.",
      "Authorized deployed-revision acceptance before this service is labeled live.",
      "Applicable source, entitlement, evaluation and protected authority checks at the point of use.",
    ],
  }));
  return {
    schemaVersion: "1",
    inventoryUpdatedAt: "2026-10-28",
    generatedAt: now.toISOString(),
    evidencePolicy: "Source-reviewed build inventory only. Request time is not verification time. Unverified means acceptance is not established, not that existing functionality is inactive. This endpoint never evaluates a user's source, grants entitlement, clears a gate or certifies deployment.",
    totalServices: services.length,
    stageServices: services.filter((service) => service.scope === "STAGE").length,
    supportingServices: services.filter((service) => service.scope === "FUNCTION").length,
    localAccepted: services.filter((service) => service.localAcceptance !== "NOT_VERIFIED").length,
    productionAccepted: services.filter((service) => service.productionAcceptance !== "NOT_VERIFIED").length,
    services,
    upgradeClasses: [
      { category: "B", description: "Infrastructure, adapters and qualification for fuller service modes.",
        activationTrigger: "Actual configured capability plus required security, consent, authority and acceptance evidence. Mandatory A safety dependencies cannot be deferred." },
      { category: "C", description: "Scale-dependent expansion beyond the bounded qualified service.",
        activationTrigger: "Measured capacity, reliability or demand exceeds the current tested scope; approve and qualify the expansion before activation." },
    ],
  };
}
