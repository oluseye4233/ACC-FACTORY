// Generates the ATANDA SPC Player End-User Guide as a PDF.
// Run with:  node scripts/src/build-spc-player-guide.mjs
// Output:    docs/SPC_Player_End_User_Guide.pdf

import { createRequire } from "node:module";
import { mkdirSync, createWriteStream } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..");
const exportRequire = createRequire(resolve(repoRoot, "lib/export/package.json"));
const PDFDocument = exportRequire("pdfkit");

const OUT_PATH = resolve(repoRoot, "docs/SPC_Player_End_User_Guide.pdf");
mkdirSync(dirname(OUT_PATH), { recursive: true });

const NAVY = "#0b1d3a";
const ACCENT = "#1f7a8c";
const GREY = "#4b5563";
const LIGHT = "#e5e7eb";

const doc = new PDFDocument({
  size: "LETTER",
  margins: { top: 64, bottom: 64, left: 64, right: 64 },
  info: {
    Title: "ATANDA SPC Player — End-User Guide",
    Author: "ATANDA Command Centre",
    Subject: "Plain-English guide to using the SPC Player cockpit, Dev Kit cards, and webhook delivery."
  }
});

doc.pipe(createWriteStream(OUT_PATH));

function hr(color = LIGHT) {
  const y = doc.y + 6;
  doc.save().strokeColor(color).lineWidth(1).moveTo(doc.page.margins.left, y).lineTo(doc.page.width - doc.page.margins.right, y).stroke().restore();
  doc.moveDown(0.8);
}

function h1(text) {
  doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(26).text(text, { align: "left" });
  doc.moveDown(0.3);
}

function h2(text) {
  doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(18).text(text);
  doc.moveDown(0.2);
}

function h3(text) {
  doc.fillColor(ACCENT).font("Helvetica-Bold").fontSize(12).text(text.toUpperCase(), { characterSpacing: 1 });
  doc.moveDown(0.15);
}

function p(text) {
  doc.fillColor(GREY).font("Helvetica").fontSize(11).text(text, { align: "left", lineGap: 2 });
  doc.moveDown(0.5);
}

function pBold(text) {
  doc.fillColor(GREY).font("Helvetica-Bold").fontSize(11).text(text, { align: "left", lineGap: 2 });
  doc.moveDown(0.5);
}

function bullets(items) {
  doc.fillColor(GREY).font("Helvetica").fontSize(11);
  for (const item of items) {
    doc.text(`•  ${item}`, { indent: 8, lineGap: 2, paragraphGap: 3 });
  }
  doc.moveDown(0.4);
}

function callout(text) {
  const startY = doc.y;
  const x = doc.page.margins.left;
  const w = doc.page.width - doc.page.margins.left - doc.page.margins.right;
  doc.save().fillColor("#f4f7fb").rect(x, startY, w, 0).restore();
  const innerPadding = 12;
  doc.fillColor(NAVY).font("Helvetica-Oblique").fontSize(11).text(text, x + innerPadding, startY + innerPadding, {
    width: w - innerPadding * 2,
    lineGap: 2
  });
  const endY = doc.y + innerPadding;
  doc.save().fillColor("#f4f7fb").rect(x, startY, w, endY - startY).fill().restore();
  doc.fillColor(NAVY).font("Helvetica-Oblique").fontSize(11).text(text, x + innerPadding, startY + innerPadding, {
    width: w - innerPadding * 2,
    lineGap: 2
  });
  doc.moveDown(0.8);
}

// ---------- COVER ----------
doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(34).text("ATANDA", { align: "left" });
doc.fillColor(ACCENT).font("Helvetica-Bold").fontSize(34).text("SPC Player");
doc.moveDown(0.5);
doc.fillColor(GREY).font("Helvetica").fontSize(16).text("End-User Guide");
doc.moveDown(0.5);
doc.fillColor(GREY).font("Helvetica-Oblique").fontSize(11).text("Cognitive Production Cockpit (Open Access)");
doc.moveDown(2);
hr(ACCENT);

callout("Note: This guide is a standalone documentation PDF explaining how to use the SPC Player. It is completely distinct from the JSON output package generated by the SPC Player itself during a run.");

h3("What the SPC Player Is (and Isn't)");
p("What it is: The SPC Player is an open-access cognitive production cockpit. It allows you to register capability briefs, execute them sequentially against a fixed set of Developer Kit cards, evaluate the results through strict governance rubrics, and package the output as a portable JSON artefact. It provides a structured, predictable way to build and review capability execution.");
p("What it is not: It is not a live integration environment. The environment sketches it references are documentation, not active connections. It does not produce certified MVP-PDDs (that remains an ARCHITECT-tier F7 capability), and it does not automatically deploy code.");

h3("Open Access and Entitlements");
p("The SPC Player is available to all authenticated users.");
bullets([
  "No Tier Required: You do not need a paid plan.",
  "No Billing or Credits: Executions do not consume project credits.",
  "No SPC-Specific Tier Gate: Normal authentication, provider availability, and platform operating limits still apply."
]);

h3("The Six Dev Kit Cards");
p("You build a run by selecting from the six available Developer Kit cards. They execute strictly in the order you select them.");
bullets([
  "ATLAS 360 PLAN: Registered planning card. Its detailed execution contract is outside the supplied SPC Player sources.",
  "SPARTAN: Scopes the Minimum Viable Product (MVP).",
  "CODE DJ: Builds the scoped MVP.",
  "BUGMXT: Debugs the result.",
  "CODON: Aligns intake against an existing MVP instead of rebuilding it.",
  "CORDON: Sequences build order."
]);

doc.addPage();

h3("Execution Flow & Profiles");
p("The SPC Player follows a rigid four-step flow:");
bullets([
  "Classify: Your plain-English brief is deterministically classified (e.g., planning, remediation, review, general).",
  "Execute: The selected cards are invoked in exact order.",
  "Evaluate: The retained results are passed to the governance evaluator.",
  "Package: Everything is assembled into a final JSON output."
]);

pBold("Profiles:");
bullets([
  "Full: Retains all stage evidence and detailed reasoning.",
  "Rapid: Optimises for concise stage content."
]);
p("Both profiles execute the cards sequentially; the difference is purely in the verbosity of the retained evidence.");

pBold("The Execution Advisory:");
p("All runs carry a mandatory PRE_BUILD execution advisory. This explicitly marks the output as a user-authorised REVERB v3 derivation, indicating its pre-production nature.");

h3("Independent Governance Scores");
p("The final evaluation assesses your run across three axes:");
bullets([
  "Clarity",
  "Truthfulness",
  "Detectability"
]);
p("Crucial Policy: These scores are always reported independently (0 to 100). The SPC Player is strictly prohibited from generating a composite or average score.");

h3("Run History and Status Glossary");
p("Runs are scoped entirely to you (the owner). You cannot see runs belonging to others, and they cannot see yours.");
bullets([
  "DRAFT: The brief is registered and cards are selected, but execution has not started.",
  "RUNNING: The engine is actively processing the sequential cards.",
  "FAILED: Execution encountered an error. You can manually retry the run from the dashboard.",
  "COMPLETED: The run finished successfully and the JSON package is ready."
]);

doc.addPage();

h3("Delivery and Safe Webhooks");
p("Once a run is COMPLETED, you can download the JSON package directly, or deliver it to an external system via webhook.");
pBold("Safe Webhook Checklist:");
bullets([
  "Must be a fully qualified HTTPS URL.",
  "Must point to a publicly resolvable IP address (no localhost, 127.0.0.1, internal network addresses, or metadata servers).",
  "Must not contain embedded credentials (e.g., https://user:pass@example.com)."
]);
p("Consent is explicit: You must authorise the endpoint for each specific run before delivery. We do not store secrets or permanent webhook subscriptions.");

h3("Current Limitations");
bullets([
  "Not Certified: Runs do not generate public verify URLs (unlike the F7 MVP-PDD process).",
  "No Automatic Send: Webhook delivery requires explicit manual confirmation per run.",
  "No Private Targets: Internal VPC or localhost webhooks are deliberately blocked.",
  "No Credentials: The webhook payload cannot be signed, and custom authentication headers are not supported.",
  "JSON Only: The SPC Player outputs a JSON package. It does not generate a PDF of the run itself."
]);

h3("Step-by-Step Quick Start");
bullets([
  "Register a Brief: Navigate to the SPC Player dashboard and click \"Register New Brief\". Enter your title, describe the capability, and choose your profile (Full or Rapid).",
  "Select Cards: Click to select the Dev Kit cards you need. The order you select them is the order they will execute.",
  "Execute: Click \"Execute Run\". Watch as the engine progresses through the stages.",
  "Review: Read the retained stage results and independent governance scores.",
  "Download or Deliver: Download the final JSON package, or authorise a public HTTPS endpoint and click \"Deliver Final Package\"."
]);

doc.addPage();

h3("Output Anatomy");
p("When you download the JSON package, you will see:");
bullets([
  "advisory: The PRE_BUILD execution authority and invoked stages.",
  "content: The array of retained stage results, each containing a verdict, content, and evidence trail.",
  "governanceEvaluation: The final textual evaluation of the run.",
  "scores: The standalone integers for clarity, truthfulness, and detectability.",
  "distributionPlan: Always records the conservative plan-only policy; an explicitly authorised webhook delivery is a separate user action and does not rewrite that policy."
]);

h3("Common Questions & Troubleshooting");
pBold("Q: My execution failed. Do I lose my brief?");
p("A: No. A FAILED run safely retains your brief and card selections. Simply open the run and click \"Retry Run\".");

pBold("Q: Why can't I authorise my webhook endpoint?");
p("A: Ensure you are using https://, and verify that the hostname resolves to a public IP. Localhost and private network IPs (like 192.168.x.x or 10.x.x.x) are blocked for security.");

pBold("Q: Where is my overall score?");
p("A: The SPC Player governance policy explicitly forbids composite scores. You must evaluate the Clarity, Truthfulness, and Detectability metrics independently.");

doc.moveDown(1);
hr(ACCENT);
doc.fillColor(GREY).font("Helvetica-Oblique").fontSize(9).text(
  `Generated ${new Date().toISOString().slice(0, 10)} · ATANDA Command Centre`,
  { align: "center" }
);

doc.end();
console.log(`Wrote ${OUT_PATH}`);
